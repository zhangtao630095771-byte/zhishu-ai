def main():
    with io.open(PATH, encoding="utf-8") as f:
        src = f.read()

    problems, done = [], 0
    for old, new in PAIRS:
        n = src.count(old)
        if n != 1:
            problems.append((n, old[:60]))
            continue
        src = src.replace(old, new)
        done += 1

    if problems:
        print("✗ 有 %d 条原文没对上（预期各 1 次），未写盘：" % len(problems))
        for n, s in problems:
            print("   命中 %d 次 → %s" % (n, s))
        sys.exit(1)

    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print("✓ 已订正 %d 处文案，文件：%s" % (done, PATH))


if __name__ == "__main__":
    main()
